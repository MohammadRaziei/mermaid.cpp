#!/usr/bin/env python3
"""Writes src/svg_text_metrics_data.h: the two faces Mermaid's sequence diagrams are measured in (Liberation Serif for the
empty font family, Liberation Sans for `sans-serif`; see tests/fonts) as design units, so any font size can be computed.

    pip install fonttools
    python3 tools/dump_font_units.py src/svg_text_metrics_data.h

What is stored per character: the advance, the ink box (xMin, xMax, yMin, yMax) and, per face, the kerning pairs of its
`kern` table and the hhea ascent and descent. svg_text_metrics.cpp turns them into what Chromium reports for an SVG <text>
(verified against getComputedTextLength() and getBBox() for 5280 strings at sizes 6 to 48).
"""
import os
import sys

from fontTools.ttLib import TTFont

FONT_DIR = os.environ.get("MERMAID_REFERENCE_FONT_DIR", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "fonts"))
FACES = (("Serif", "LiberationSerif-Regular.ttf"), ("Sans", "LiberationSans-Regular.ttf"))
CODES = list(range(32, 127)) + list(range(160, 256)) + [0xFB02]  # `ﬂ` starts an encoded entity code (`#35;` is written `ﬂ°°35¶ß`)


def face_tables(file_name):
    font = TTFont(os.path.join(FONT_DIR, file_name))
    cmap, hmtx, glyf, hhea = font.getBestCmap(), font["hmtx"], font["glyf"], font["hhea"]
    kern = {}
    for table in font["kern"].kernTables:
        kern.update(table.kernTable)
    glyphs = []
    for code in CODES:
        name = cmap[code]
        g = glyf[name]
        ink = g.numberOfContours != 0
        glyphs.append((code, hmtx[name][0], 1 if ink else 0, g.xMin if ink else 0, g.xMax if ink else 0, g.yMin if ink else 0, g.yMax if ink else 0))
    pairs = []
    for a in CODES:
        for b in CODES:
            value = kern.get((cmap[a], cmap[b]), 0)
            if value:
                pairs.append((a, b, value))
    return font["head"].unitsPerEm, hhea.ascent, -hhea.descent, glyphs, pairs


def rows(items):
    return ", ".join("{" + ", ".join(str(v) for v in item) + "}" for item in items)


def main(out_path):
    text = ["// svg_text_metrics_data.h (private) - generated by tools/dump_font_units.py; do not edit.",
            "// Liberation Serif and Liberation Sans Regular in design units (see the tool for what is stored).",
            "#pragma once", "", "namespace mermaid::detail {", "",
            "struct svg_glyph { unsigned short code; int advance; int ink; int x_min, x_max, y_min, y_max; };",
            "struct svg_pair { unsigned short first, second; int value; };", ""]
    for name, file_name in FACES:
        upem, ascent, descent, glyphs, pairs = face_tables(file_name)
        text += [f"inline constexpr int k{name}UnitsPerEm = {upem};",
                 f"inline constexpr int k{name}Ascent = {ascent};",
                 f"inline constexpr int k{name}Descent = {descent};",
                 f"inline constexpr svg_glyph k{name}Glyphs[] = {{{rows(glyphs)}}};",
                 f"inline constexpr svg_pair k{name}Pairs[] = {{{rows(pairs)}}};", ""]
    text += ["}  // namespace mermaid::detail", ""]
    with open(out_path, "w") as f:
        f.write("\n".join(text))
    print("written", out_path)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/svg_text_metrics_data.h")
