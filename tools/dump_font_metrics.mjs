// Measures the advance widths and kerning of the font Mermaid's labels get in a browser and writes
// src/browser_font_metrics.cpp. Needs: npm i @sparticuz/chromium puppeteer-core
//   node tools/dump_font_metrics.mjs src/browser_font_metrics.cpp
// Font: font-family "Recursive Variable", arial, sans-serif at 14px (Mermaid 12.2 default), in the four faces Markdown
// labels use. The family is pinned to the Liberation Sans of tests/fonts, as tools/render_all_references.mjs does.
import chromium from '@sparticuz/chromium';
import puppeteer from 'puppeteer-core';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const out = process.argv[2];
const fontDir = process.env.MERMAID_REFERENCE_FONT_DIR ||
  path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'tests', 'fonts');
const faces = [['Regular', 'normal', 'normal'], ['Bold', 'bold', 'normal'], ['Italic', 'normal', 'italic'], ['BoldItalic', 'bold', 'italic']];
const fontCss = ['arial', 'Recursive Variable'].flatMap(family => faces.map(([file, weight, style]) =>
  `@font-face{font-family:"${family}";font-weight:${weight};font-style:${style};src:url(data:font/ttf;base64,` +
  `${fs.readFileSync(path.join(fontDir, `LiberationSans-${file}.ttf`)).toString('base64')});}`)).join('');
const browser = await puppeteer.launch({args: chromium.args, executablePath: await chromium.executablePath(), headless: 'shell'});
const page = await browser.newPage();
await page.setContent('<html><head><style>' + fontCss + '</style></head><body></body></html>');
await page.evaluate(async () => { await Promise.all([...document.fonts].map(f => f.load())); await document.fonts.ready; });
const data = await page.evaluate((faces) => {
  const span = document.createElement('span');
  document.body.appendChild(span);
  const result = [];
  for (const [, weight, style] of faces) {
    span.style.cssText = `position:absolute;white-space:pre;font-family:"Recursive Variable",arial,sans-serif;font-size:14px;font-weight:${weight};font-style:${style};`;
    const w = (s) => { span.textContent = s; return span.getBoundingClientRect().width; };
    const codes = [];
    for (let c = 32; c <= 126; c++) codes.push(c);
    for (let c = 160; c <= 255; c++) codes.push(c);
    const advances = codes.map((c) => [c, Math.round(w(String.fromCharCode(c)) * 64)]);
    const adv = new Map(advances);
    const kerning = [];
    for (let a = 32; a <= 126; a++) for (let b = 32; b <= 126; b++) {
      const d = Math.round((w(String.fromCharCode(a, b)) - adv.get(a) / 64 - adv.get(b) / 64) * 64);
      if (d !== 0) kerning.push([a, b, d]);
    }
    result.push({advances, kerning});
  }
  return result;
}, faces);
await browser.close();

let src = '// Generated by tools/dump_font_metrics.mjs - do not edit.\n// Advances and kerning in 1/64 px at 14px, as a headless Chromium measures them.\n#include "browser_font_metrics.h"\n\nnamespace mermaid::detail {\n\n';
faces.forEach(([name], i) => {
  src += `const font_advance k${name}Advances[] = {\n`;
  for (let j = 0; j < data[i].advances.length; j += 8) src += '    ' + data[i].advances.slice(j, j + 8).map(([c, u]) => `{${c},${u}}`).join(',') + ',\n';
  src += '};\n';
  src += `const font_kerning k${name}Kerning[] = {\n`;
  for (let j = 0; j < data[i].kerning.length; j += 10) src += '    ' + data[i].kerning.slice(j, j + 10).map(([a, b, u]) => `{${a},${b},${u}}`).join(',') + ',\n';
  src += '};\n\n';
});
src += 'const font_table kFontTables[4] = {\n';
faces.forEach(([name]) => { src += `    {k${name}Advances, sizeof(k${name}Advances) / sizeof(k${name}Advances[0]), k${name}Kerning, sizeof(k${name}Kerning) / sizeof(k${name}Kerning[0])},\n`; });
src += '};\n\n}  // namespace mermaid::detail\n';
fs.writeFileSync(out, src);
console.log(data.map((d) => d.advances.length + ' advances, ' + d.kerning.length + ' kerning pairs').join(' | '));
