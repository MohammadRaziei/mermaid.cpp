// Measures what utils.calculateTextDimensions sees for sequence diagrams (SVG <text>, 16px) and writes
// src/svg_text_metrics_data.h: the serif face (Mermaid measures with an empty font-family, so the browser default
// "Times New Roman" answers; tests/fonts pins it to Liberation Serif) with advances, the right overhang of the last glyph
// and the kerning pairs, plus which characters make the height 18 instead of 17 in both faces.
//   node tools/dump_svg_text_metrics.mjs src/svg_text_metrics_data.h
import chromium from '@sparticuz/chromium';
import puppeteer from 'puppeteer-core';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const out = process.argv[2];
const fontDir = process.env.MERMAID_REFERENCE_FONT_DIR ||
  path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'tests', 'fonts');
const b64 = (f) => fs.readFileSync(path.join(fontDir, f)).toString('base64');
const fontCss = `@font-face{font-family:"Times New Roman";src:url(data:font/ttf;base64,${b64('LiberationSerif-Regular.ttf')});}` +
  `@font-face{font-family:"sans";src:url(data:font/ttf;base64,${b64('LiberationSans-Regular.ttf')});}`;
const browser = await puppeteer.launch({args: chromium.args, executablePath: await chromium.executablePath(), headless: 'shell'});
const page = await browser.newPage();
await page.setContent('<html><head><style>' + fontCss + '</style></head><body><svg id="s" width="900" height="100"></svg></body></html>');
await page.evaluate(async () => { await Promise.all([...document.fonts].map(f => f.load())); await document.fonts.ready; });
const data = await page.evaluate(() => {
  const svg = document.getElementById('s');
  const measure = (family, text) => {
    const t = document.createElementNS('http://www.w3.org/2000/svg', 'text');
    t.style.fontSize = '16px'; t.style.fontWeight = '400'; t.style.whiteSpace = 'pre'; if (family) t.style.fontFamily = family;  // `pre`: blanks keep their width, so pairs with a blank can be measured
    t.textContent = text; svg.appendChild(t);
    const b = t.getBBox(), len = t.getComputedTextLength();
    t.remove();
    return {w: b.width, h: Math.round(b.height), len};
  };
  const codes = [];
  for (let c = 33; c <= 126; c++) codes.push(c);
  for (let c = 160; c <= 255; c++) codes.push(c);
  codes.push(0xFB02);  // `ﬂ`, the first character of an encoded entity code (`#35;` is written `ﬂ°°35¶ß`)
  const serif = {}, sans = {};
  const res = {advances: [], overhang: [], overhang_sans: [], tall_serif: [], tall_sans: [], kerning: []};
  for (const family of [null, 'sans']) {
    for (const c of codes) {
      const m = measure(family, String.fromCharCode(c));
      if (m.h !== 17) (family ? res.tall_sans : res.tall_serif).push([c, m.h]);
      if (family) res.overhang_sans.push([c, Math.round((m.w - m.len) * 256)]);
      if (!family) { res.advances.push([c, Math.round(m.len * 256)]); res.overhang.push([c, Math.round((m.w - m.len) * 256)]); serif[c] = m.len; }
    }
  }
  const space = measure(null, ' ').len;
  res.space = Math.round(space * 256);
  serif[32] = space;
  for (let a = 32; a <= 126; a++) for (let b = 32; b <= 126; b++) {
    const d = Math.round((measure(null, String.fromCharCode(a, b)).len - serif[a] - serif[b]) * 256);
    if (d !== 0) res.kerning.push([a, b, d]);  // lengths are multiples of 1/64 px: every difference is a real kerning value
  }
  return res;
});
await browser.close();
const list = (rows) => rows.map(r => `{${r.join(', ')}}`).join(', ');
const text = `// svg_text_metrics_data.h (private) - generated by tools/dump_svg_text_metrics.mjs; do not edit.
// Liberation Serif Regular at 16px as an SVG <text> in Chromium, units of 1/256 px.
#pragma once

namespace mermaid::detail {

struct svg_glyph { unsigned short code; int units; };
struct svg_pair { unsigned char first, second; int units; };

inline constexpr int kSvgSpaceUnits = ${data.space};
inline constexpr svg_glyph kSerifAdvance[] = {${list(data.advances)}};
inline constexpr svg_glyph kSerifOverhang[] = {${list(data.overhang)}};
inline constexpr svg_pair kSerifKerning[] = {${list(data.kerning.sort((x, y) => x[0] - y[0] || x[1] - y[1]))}};
// code, rounded bbox height when it is not 17
inline constexpr svg_glyph kSerifTall[] = {${list(data.tall_serif)}};
// how far the last glyph of a sans-serif run reaches beyond its advance (bbox width - computed length), units of 1/256 px
inline constexpr svg_glyph kSansOverhang[] = {${list(data.overhang_sans)}};
inline constexpr svg_glyph kSansTall[] = {${list(data.tall_sans)}};

}  // namespace mermaid::detail
`;
fs.writeFileSync(out, text);
console.log(`advances ${data.advances.length}, kerning ${data.kerning.length}, tall serif ${data.tall_serif.length}, tall sans ${data.tall_sans.length}`);
